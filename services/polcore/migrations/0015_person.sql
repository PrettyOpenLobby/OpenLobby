-- person: the admin panel's record of one human, across PlayOnline and the games
-- (services/adminpeople.py, the People section).
--
-- A person is made when the panel first needs one: for a PlayOnline account the
-- first time staff open, link or note it (so the accounts that existed before
-- this table need nothing copied), otherwise by staff ("New person", or while
-- linking a login). Logins a player has PROVED are not copied here: the panel
-- reads them where they are kept (game_link for the games, discord_link for the
-- Discord bot) through the account's members, every time it shows the person.
--
-- person          name is what staff see; merged_into is set when staff merge
--                 this person into another one: the row stays so an old link
--                 or a history entry naming it still leads somewhere.
-- person_link     a login that belongs to the person. system is "pol" (key = the
--                 PlayOnline ID: the person's own account, how = 'proven', made
--                 with the person), a game's account system (the same keys
--                 game_link uses; a game without one uses its panel module key)
--                 or "discord" (key = the Discord user id). how = 'staff' rows
--                 are what staff linked by hand, with who, when and why. One
--                 login belongs to one person: UNIQUE (system, key).
-- person_note     what staff wrote about the person.
--
-- Times are unix seconds (DOUBLE PRECISION), as in the admin_* tables (0003).
-- No foreign key reaches the account tables: a panel run without the PlayOnline
-- core (POL_ADMIN_CORE=none) has persons and no accounts.

CREATE TABLE person (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    created_at  DOUBLE PRECISION NOT NULL,
    created_by  TEXT,
    merged_into BIGINT REFERENCES person(id)
);
CREATE INDEX person_name ON person (lower(name));

CREATE TABLE person_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id  BIGINT NOT NULL REFERENCES person(id),
    system     TEXT NOT NULL,
    key        TEXT NOT NULL,
    name       TEXT NOT NULL DEFAULT '',
    how        TEXT NOT NULL CHECK (how IN ('proven', 'staff')),
    "by"       TEXT,
    why        TEXT NOT NULL DEFAULT '',
    at         DOUBLE PRECISION NOT NULL,
    UNIQUE (system, key)
);
CREATE INDEX person_link_person ON person_link (person_id);

CREATE TABLE person_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id  BIGINT NOT NULL REFERENCES person(id),
    "by"       TEXT NOT NULL,
    at         DOUBLE PRECISION NOT NULL,
    text       TEXT NOT NULL
);
CREATE INDEX person_note_person ON person_note (person_id, at);
